import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import vm from 'node:vm';
import ts from 'typescript';
const require=createRequire(import.meta.url);
const {NextRequest,NextResponse}=require('next/server');
const testProcess={env:{NODE_ENV:'development',SPOTIFY_CLIENT_ID:'test-client',SPOTIFY_CLIENT_SECRET:'test-secret',SPOTIFY_REDIRECT_URI:'http://127.0.0.1:3000/api/spotify/callback'}};
let exchanges=0;
function load(file,mocks={}){const exports={};vm.runInNewContext(ts.transpileModule(readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports,require:n=>mocks[n]??require(n),process:testProcess,URL,URLSearchParams,Buffer,Date,AbortSignal,console,fetch:async()=>{exchanges++;return Response.json({access_token:'fake-access',refresh_token:'fake-refresh',expires_in:3600});}});return exports;}
const spotify=load('app/lib/spotify.ts');
const origin=load('lib/http/request-origin.ts');
const mocks={'next/server':{NextRequest,NextResponse},'@/app/lib/spotify':spotify,'@/lib/http/request-origin':origin};
const login=load('app/api/spotify/login/route.ts',mocks);
let response=await login.GET(new NextRequest('http://localhost:3000/api/spotify/login',{headers:{host:'localhost:3000'}}));
assert.equal(response.headers.get('location'),'http://127.0.0.1:3000/api/spotify/login');
assert.equal(response.cookies.get(spotify.SPOTIFY_STATE_COOKIE),undefined);
response=await login.GET(new NextRequest('http://localhost:3000/api/spotify/login',{headers:{host:'127.0.0.1:3000'}}));
const location=new URL(response.headers.get('location'));
assert.equal(location.origin,'https://accounts.spotify.com');
assert.equal(location.searchParams.get('redirect_uri'),testProcess.env.SPOTIFY_REDIRECT_URI);
const state=response.cookies.get(spotify.SPOTIFY_STATE_COOKIE).value;
assert.equal(location.searchParams.get('state'),state);
assert.equal(response.headers.get('cache-control'),'no-store');
const callback=load('app/api/spotify/callback/route.ts',mocks);
const callbackRequest=(returned,cookie)=>new NextRequest(`http://127.0.0.1:3000/api/spotify/callback?code=test-code&state=${returned}`,{headers:{cookie:`${spotify.SPOTIFY_STATE_COOKIE}=${cookie}`}});
response=await callback.GET(callbackRequest('wrong',state));assert.match(response.headers.get('location'),/spotify_state_mismatch/);assert.equal(exchanges,0);
response=await callback.GET(callbackRequest(state,state));assert.equal(exchanges,1);
assert.equal(response.headers.get('location'),'http://127.0.0.1:3000/spotify?connected=true');
assert.equal(response.cookies.get(spotify.SPOTIFY_ACCESS_TOKEN_COOKIE).value,'fake-access');
assert.equal(response.cookies.get(spotify.SPOTIFY_REFRESH_TOKEN_COOKIE).value,'fake-refresh');
assert.equal(response.cookies.get(spotify.SPOTIFY_STATE_COOKIE).maxAge,0);
assert.equal(response.cookies.get(spotify.SPOTIFY_ACCESS_TOKEN_COOKIE).secure,false);
const cookie=response.cookies.getAll().filter(c=>c.maxAge!==0).map(c=>`${c.name}=${c.value}`).join('; ');
const connected=await spotify.getValidSpotifyAccessToken(new NextRequest('http://127.0.0.1:3000/api/spotify/playlists',{headers:{cookie}}));assert.equal(connected.accessToken,'fake-access');assert.equal(exchanges,1);
console.log('PASS canonical Spotify navigation, fresh state, rejected mismatched state, callback cookies and subsequent authenticated playlist token');
